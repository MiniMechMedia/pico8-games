def norm(rows, name):
    rows = list(rows)
    assert len(rows) <= 24, f"{name}: {len(rows)} rows"
    return [E] * (24 - len(rows)) + rows  # feet-anchor


def build_sheet():
    page = [['0'] * 128 for _ in range(128)]
    for i, rows in enumerate(POSES):
        rows = norm(rows, NAMES[i])
        ox, oy = (i % 8) * 16, (i // 8) * 24
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch != '0':
                    page[oy + y][ox + x] = ch
    return page


def gfx_section(page):
    lines = ["".join(r) for r in page]
    while lines and set(lines[-1]) == {'0'}:
        lines.pop()
    return "__gfx__\n" + "\n".join(lines) + "\n"


def preview(page, path, scale=6):
    HH = 72
    img = Image.new("RGB", ((128 + 4) * scale, (HH + 40) * scale), PAL['1'])
    px = img.load()

    def blit(ox, oy, sx, sy, w, h, swap=None):
        for y in range(h):
            for x in range(w):
                ch = page[sy + y][sx + x]
                if ch == '0':
                    continue
                if swap and ch in swap:
                    ch = swap[ch]
                c = PAL[ch]
                for dy in range(scale):
                    for dx in range(scale):
                        px[(ox + x) * scale + dx, (oy + y) * scale + dy] = c

    blit(2, 2, 0, 0, 128, HH)
    for mi, swap in enumerate(SWAPS.values()):
        blit(2 + mi * 20, HH + 8, 0, 0, 16, 24, swap)
    img.save(path)


if __name__ == "__main__":
    page = build_sheet()
    open("gfx.txt", "w").write(gfx_section(page))
    preview(page, "sheet.png")
