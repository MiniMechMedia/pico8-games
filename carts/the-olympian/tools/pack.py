"""Pack px9 blobs from build/ into pico-8 data carts + emit lua index.

Data cart layout: blobs packed back-to-back through gfx (0x0000-0x1fff),
map (0x2000-0x2fff), gff (0x3000-0x30ff) = 12544 bytes per cart.
Blobs never straddle carts. Emits ../imgindex.lua used by the main cart.

Usage: python pack.py
"""
import os
from glob import glob

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
CAPACITY = 8192 + 4096 + 256
HEX = '0123456789abcdef'

CART_HEADER = '''pico-8 cartridge // http://www.pico-8.com
version 42
__lua__
-- the olympian: image data cart (generated by tools/pack.py)
'''


def sections_from_bytes(data):
    """Encode up to 12544 bytes into __gfx__/__map__/__gff__ section text."""
    data = data + b'\x00' * (CAPACITY - len(data))
    out = []
    out.append('__gfx__')
    for line in range(128):
        chunk = data[line * 64:(line + 1) * 64]
        # gfx text is one hex char per pixel; low nibble of each byte comes first
        out.append(''.join(HEX[b & 0xf] + HEX[b >> 4] for b in chunk))
    out.append('__gff__')
    for line in range(2):
        chunk = data[8192 + 4096 + line * 128:8192 + 4096 + (line + 1) * 128]
        out.append(''.join(HEX[b >> 4] + HEX[b & 0xf] for b in chunk))
    out.append('__map__')
    for line in range(32):
        chunk = data[8192 + line * 128:8192 + (line + 1) * 128]
        out.append(''.join(HEX[b >> 4] + HEX[b & 0xf] for b in chunk))
    return '\n'.join(out) + '\n'


def write_cart(path, data):
    with open(path, 'w') as f:
        f.write(CART_HEADER + sections_from_bytes(data))


def pack(blob_names=None):
    blobs = []
    for blob_path in sorted(glob(os.path.join(TOOLS, 'build', '*.blob'))):
        name = os.path.splitext(os.path.basename(blob_path))[0]
        if blob_names is not None and name not in blob_names:
            continue
        with open(blob_path, 'rb') as f:
            data = f.read()
        with open(os.path.join(TOOLS, 'build', f'{name}.pal')) as f:
            pal = f.read().strip()
        blobs.append((name, data, pal))

    # first-fit decreasing
    blobs.sort(key=lambda b: -len(b[1]))
    carts = []  # each: list of (name, data, pal)
    for name, data, pal in blobs:
        for cart in carts:
            used = sum(len(d) for _, d, _ in cart)
            if used + len(data) <= CAPACITY:
                cart.append((name, data, pal))
                break
        else:
            carts.append([(name, data, pal)])

    index_lines = ['img_index={']
    for ci, cart in enumerate(carts):
        packed = b''
        for name, data, pal in cart:
            index_lines.append(f' {name}={{{ci},{len(packed)},{len(data)},"{pal}"}},')
            packed += data
        write_cart(os.path.join(ROOT, f'oly_img{ci}.p8'), packed)
        print(f'oly_img{ci}.p8: {len(packed)}/{CAPACITY} bytes, '
              f'{len(cart)} images ({", ".join(n for n, _, _ in cart)})')
    index_lines.append('}')
    with open(os.path.join(ROOT, 'imgindex.lua'), 'w') as f:
        f.write('\n'.join(index_lines) + '\n')


if __name__ == '__main__':
    pack()
